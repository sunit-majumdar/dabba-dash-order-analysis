"""
SYNTHETIC DATA - Dabba Dash (fictional food-delivery company) order log.

Every row in the output file is generated by this script with a fixed random
seed. No real company data is used. Dabba Dash does not exist.

Run:  python generate_orders.py
Out:  dabba_dash_orders.csv  (one row per order, with realistic data-quality issues)
"""
import numpy as np
import pandas as pd

SEED = 75
rng = np.random.default_rng(SEED)

N_BASE = 15_000
START, END = pd.Timestamp("2025-01-01"), pd.Timestamp("2026-06-30")

# ---------------------------------------------------------------- dates
days = pd.date_range(START, END, freq="D")
t = np.arange(len(days)) / (len(days) - 1)
w = 1.0 + 0.9 * t                                        # business grows over time
w *= np.where(days.dayofweek >= 4, 1.18, 1.0)           # Fri-Sun busier
diwali = pd.Timestamp("2025-10-20")
w *= 1.0 + 0.55 * np.exp(-0.5 * ((days - diwali).days / 12.0) ** 2)  # festive spike
w /= w.sum()
order_dates = rng.choice(days, size=N_BASE, p=w)

# ---------------------------------------------------------------- time of day
hour_w = {10: 1, 11: 2, 12: 6, 13: 7, 14: 4, 15: 2, 16: 2, 17: 3,
          18: 5, 19: 8, 20: 10, 21: 9, 22: 5, 23: 2}
hours = rng.choice(list(hour_w), size=N_BASE, p=np.array(list(hour_w.values())) / sum(hour_w.values()))
minutes = rng.integers(0, 60, N_BASE)

# ---------------------------------------------------------------- categories
city_p = {"Mumbai": .28, "Bengaluru": .24, "Delhi": .18, "Pune": .12, "Hyderabad": .11, "Thane": .07}
city = rng.choice(list(city_p), size=N_BASE, p=list(city_p.values()))

cuisine_p = {"Biryani": .20, "North Indian": .18, "Pizza": .14, "Burgers": .12,
             "Chinese": .12, "Healthy": .08, "Desserts": .08, "South Indian": .08}
cuisine = rng.choice(list(cuisine_p), size=N_BASE, p=list(cuisine_p.values()))

cust_new = rng.random(N_BASE) < 0.35
payment = rng.choice(["UPI", "Card", "COD", "Wallet"], size=N_BASE, p=[.52, .20, .18, .10])

# ---------------------------------------------------------------- money
base_value = {"Biryani": 380, "North Indian": 420, "Pizza": 460, "Burgers": 280,
              "Chinese": 340, "Healthy": 360, "Desserts": 220, "South Indian": 260}
city_mult = {"Mumbai": 1.10, "Delhi": 1.05, "Bengaluru": 1.00, "Hyderabad": .95, "Pune": .95, "Thane": .90}

disc_choices = np.array([0, 5, 10, 15, 20, 25, 30, 40])
p_new = [.25, .05, .20, .10, .20, .10, .07, .03]
p_ret = [.55, .08, .15, .08, .08, .03, .02, .01]
discount = np.where(cust_new,
                    rng.choice(disc_choices, N_BASE, p=p_new),
                    rng.choice(disc_choices, N_BASE, p=p_ret))

order_value = np.array([base_value[c] * city_mult[k] for c, k in zip(cuisine, city)])
order_value = order_value * rng.lognormal(mean=0.0, sigma=0.45, size=N_BASE)
order_value = order_value * (1 + 0.006 * discount)
order_value = np.round(np.clip(order_value, 60, 4000), 0)

distance = np.round(np.clip(rng.gamma(2.2, 1.4, N_BASE), 0.3, 12.0), 1)
fee = 15 + 4 * distance
free = (order_value > 499) & (rng.random(N_BASE) < 0.6)
delivery_fee = np.round(np.where(free, 0, fee), 0)

# ---------------------------------------------------------------- delivery time
peak = np.where((hours >= 19) & (hours <= 22), 6.0, np.where((hours >= 12) & (hours <= 14), 3.0, 0.0))
city_delay = {"Bengaluru": 4, "Mumbai": 3, "Delhi": 2, "Hyderabad": 1, "Pune": -1, "Thane": -1}
delivery_time = (10 + 3.2 * distance + peak
                 + np.array([city_delay[k] for k in city])
                 + rng.normal(0, 4, N_BASE))
delivery_time = np.round(np.clip(delivery_time, 8, None), 0)

# ---------------------------------------------------------------- status / rating
p_cancel = 0.04 + 0.05 * (payment == "COD") + 0.02 * cust_new
cancelled = rng.random(N_BASE) < p_cancel
status = np.where(cancelled, "Cancelled", "Delivered")

rating_raw = 4.5 - 0.03 * np.clip(delivery_time - 30, 0, None) + rng.normal(0, 0.7, N_BASE)
rating = np.clip(np.round(rating_raw), 1, 5)
rates = (~cancelled) & (rng.random(N_BASE) < 0.62)

df = pd.DataFrame({
    "order_id": [f"DD{100000 + i}" for i in range(N_BASE)],
    "order_date": pd.to_datetime(order_dates).strftime("%d-%m-%Y"),
    "order_time": [f"{h:02d}:{m:02d}" for h, m in zip(hours, minutes)],
    "city": city,
    "cuisine": cuisine,
    "customer_type": np.where(cust_new, "New", "Returning"),
    "payment_method": payment,
    "order_value_inr": order_value,
    "discount_pct": discount,
    "delivery_fee_inr": delivery_fee,
    "distance_km": distance,
    "delivery_time_min": np.where(cancelled, np.nan, delivery_time),
    "rating": np.where(rates, rating, np.nan),
    "status": status,
})

# ---------------------------------------------------------------- data-quality issues
# 1. spelling variants in city
m = (df.city == "Bengaluru") & (rng.random(N_BASE) < 0.12)
df.loc[m, "city"] = rng.choice(["Bangalore", "bengaluru ", "BENGALURU"], m.sum())
m = (df.city == "Mumbai") & (rng.random(N_BASE) < 0.04)
df.loc[m, "city"] = "mumbai"
m = (df.city == "Delhi") & (rng.random(N_BASE) < 0.06)
df.loc[m, "city"] = "New Delhi"

# 2. blanks in categorical columns
df.loc[rng.random(N_BASE) < 0.02, "customer_type"] = np.nan
df.loc[rng.random(N_BASE) < 0.015, "payment_method"] = np.nan

# 3. impossible delivery times on delivered orders (clock errors)
bad = (df.status == "Delivered") & (rng.random(N_BASE) < 0.004)
df.loc[bad, "delivery_time_min"] = rng.integers(240, 700, bad.sum())

# 4. exact duplicate rows
dups = df.sample(n=int(0.012 * N_BASE), random_state=SEED)
df = pd.concat([df, dups], ignore_index=True)
df = df.sample(frac=1.0, random_state=SEED).reset_index(drop=True)

df.to_csv("dabba_dash_orders.csv", index=False)
print(df.shape)
